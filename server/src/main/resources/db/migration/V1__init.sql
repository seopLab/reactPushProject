-- 긴 문자열은 text 대신 길이 없는 varchar 를 쓴다 (PostgreSQL 에선 text 와 같고, H2 에서 JPA String 검증이 통과함)

-- ① 회원 ---------------------------------------------------------------

create table members (
	id               bigint generated by default as identity primary key,
	email            varchar(255) not null,
	password_hash    varchar(255) not null,
	nickname         varchar(50)  not null,
	birth_date       date,
	region_name      varchar(100),               -- 기준 지역 이름 (예: 경기도 시흥시)
	lat              numeric(10, 7),
	lng              numeric(10, 7),
	alert_radius_km  int          not null default 10,
	household_size   int,
	house_owned      varchar(30),                -- 주택 보유 상태 (무주택 / 1주택 등)
	has_bank_account boolean      not null default false,
	account_months   int,                        -- 청약통장 가입 기간(개월)
	created_at       timestamp    not null default current_timestamp,
	deleted_at       timestamp,                  -- 탈퇴 시각 (null = 활성 회원)
	constraint uq_members_email unique (email)
);

create table member_supply_types (
	member_id   bigint      not null,
	supply_type varchar(30) not null,            -- 희망 공급 유형
	constraint pk_member_supply_types primary key (member_id, supply_type),
	constraint fk_member_supply_types_member foreign key (member_id) references members (id) on delete cascade
);

create table member_special_conditions (
	member_id bigint      not null,
	condition varchar(30) not null,              -- 특별공급 조건 (신혼부부, 생애최초 등)
	constraint pk_member_special_conditions primary key (member_id, condition),
	constraint fk_member_special_conditions_member foreign key (member_id) references members (id) on delete cascade
);

create table member_documents (
	member_id bigint      not null,
	doc_type  varchar(50) not null,              -- 서류 종류
	checked   boolean     not null default false,
	constraint pk_member_documents primary key (member_id, doc_type),
	constraint fk_member_documents_member foreign key (member_id) references members (id) on delete cascade
);

-- ② 공고 ---------------------------------------------------------------

create table housing_notices (
	id               bigint generated by default as identity primary key,
	source           varchar(20)  not null,      -- 출처 (APPLYHOME / LH 등)
	source_notice_no varchar(50)  not null,      -- 출처 쪽 공고 번호
	house_manage_no  varchar(50),
	name             varchar(200) not null,
	region           varchar(100),
	address          varchar(300),
	lat              numeric(10, 7),
	lng              numeric(10, 7),
	supply_type      varchar(30),
	house_type       varchar(30),
	builder          varchar(100),
	contact          varchar(100),
	notice_date      date,
	receipt_start    date,
	receipt_end      date,
	winner_date      date,
	detail_url       varchar(500),
	notice_pdf_url   varchar(500),
	created_at       timestamp    not null default current_timestamp,
	updated_at       timestamp    not null default current_timestamp,
	constraint uq_housing_notices_source unique (source, source_notice_no)
);

create index idx_housing_notices_receipt_end on housing_notices (receipt_end);
create index idx_housing_notices_region on housing_notices (region);

create table notice_supply_items (
	id              bigint generated by default as identity primary key,
	notice_id       bigint        not null,
	house_type_name varchar(50),                 -- 주택형 (예: 084.9632A)
	area            numeric(8, 2),               -- 전용면적(㎡)
	supply_count    int,
	constraint fk_notice_supply_items_notice foreign key (notice_id) references housing_notices (id) on delete cascade
);

create index idx_notice_supply_items_notice on notice_supply_items (notice_id);

-- ③ 관심·알림 ----------------------------------------------------------

create table favorites (
	member_id  bigint    not null,
	notice_id  bigint    not null,
	created_at timestamp not null default current_timestamp,
	constraint pk_favorites primary key (member_id, notice_id),
	constraint fk_favorites_member foreign key (member_id) references members (id) on delete cascade,
	constraint fk_favorites_notice foreign key (notice_id) references housing_notices (id) on delete cascade
);

create index idx_favorites_notice on favorites (notice_id);

create table push_tokens (
	id         bigint generated by default as identity primary key,
	member_id  bigint       not null,
	expo_token varchar(255) not null,
	platform   varchar(20),                      -- ios / android
	created_at timestamp    not null default current_timestamp,
	constraint uq_push_tokens_expo_token unique (expo_token),
	constraint fk_push_tokens_member foreign key (member_id) references members (id) on delete cascade
);

create index idx_push_tokens_member on push_tokens (member_id);

create table notification_settings (
	member_id   bigint  primary key,
	new_notice  boolean not null default true,
	deadline    boolean not null default true,
	winner      boolean not null default true,
	quiet_hours boolean not null default true,
	quiet_start time    not null default '22:00:00',
	quiet_end   time    not null default '08:00:00',
	constraint fk_notification_settings_member foreign key (member_id) references members (id) on delete cascade
);

create table notification_logs (
	id        bigint generated by default as identity primary key,
	member_id bigint      not null,
	notice_id bigint      not null,
	type      varchar(30) not null,              -- NEW_NOTICE / DEADLINE_D3 / DEADLINE_D1 / WINNER 등
	sent_at   timestamp   not null default current_timestamp,
	constraint uq_notification_logs unique (member_id, notice_id, type),   -- 같은 알림 1회만
	constraint fk_notification_logs_member foreign key (member_id) references members (id) on delete cascade,
	constraint fk_notification_logs_notice foreign key (notice_id) references housing_notices (id) on delete cascade
);

-- ④ AI·수집 ------------------------------------------------------------

create table notice_analyses (
	id          bigint generated by default as identity primary key,
	notice_id   bigint      not null,
	status      varchar(20) not null,            -- PENDING / DONE / FAILED
	model       varchar(50),
	result_json varchar,                         -- Gemini 분석 결과 JSON
	analyzed_at timestamp,
	constraint uq_notice_analyses_notice unique (notice_id),
	constraint fk_notice_analyses_notice foreign key (notice_id) references housing_notices (id) on delete cascade
);

create table ai_chat_messages (
	id         bigint generated by default as identity primary key,
	member_id  bigint      not null,
	notice_id  bigint,                           -- 특정 공고 없이 묻는 질문이면 null
	role       varchar(20) not null,             -- USER / ASSISTANT
	content    varchar     not null,
	created_at timestamp   not null default current_timestamp,
	constraint fk_ai_chat_messages_member foreign key (member_id) references members (id) on delete cascade,
	constraint fk_ai_chat_messages_notice foreign key (notice_id) references housing_notices (id) on delete set null
);

create index idx_ai_chat_messages_member on ai_chat_messages (member_id, created_at);

create table collect_runs (
	id          bigint generated by default as identity primary key,
	source      varchar(20) not null,
	started_at  timestamp   not null default current_timestamp,
	finished_at timestamp,
	ok          boolean,                         -- null = 실행 중
	total       int         not null default 0,
	inserted    int         not null default 0,
	error       varchar
);
